/// Look up an endpoint; `None` means the action is not in the inventory.
pub fn lookup(scope: &str, action: &str) -> Option<&'static Endpoint> {
    ENDPOINTS
        .iter()
        .find(|e| e.scope == scope && e.action == action)
}
